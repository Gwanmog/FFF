def get_movie_data(country: str) -> list[dict]:
    movies = COUNTRY_MOVIES.get(country, [])
    if not movies:
        query = urllib.parse.quote(f"best movies from {country}")
        return [{"title": f"Search for {country} films", "genre": "", "link": f"https://www.google.com/search?q={query}"}]
    return [
        {
            "title": m,
            "genre": MOVIE_GENRES.get(m, ""),
            "link": _watch_link(m),
        }
        for m in movies[:10]
    ]
