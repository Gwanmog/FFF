def get_spotify_link(country: str) -> str:
    """Return a Spotify search URL for a country's music."""
    query = urllib.parse.quote(f"{country} traditional modern music")
    return f"https://open.spotify.com/search/{query}"


def get_music_data(country: str) -> dict:
    artists = COUNTRY_ARTISTS.get(country, [])
    playlist_query = urllib.parse.quote(f"{country} music mix traditional modern")
    return {
        "artists": artists,
        "spotify_search": f"https://open.spotify.com/search/{playlist_query}",
    }


